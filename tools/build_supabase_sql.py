"""Build supabase/01_schema.sql from the Postgres migrations.

The owner creates the Supabase database by pasting that one file into the
Supabase SQL editor. It is every migrations/*.postgres.sql file in order,
plus the schema_migrations rows that tell the app's migration runner
(tools/db.py) they are already applied.

Run this after adding a migration (tests/test_migrations.py fails until the
file matches):
    python tools/build_supabase_sql.py
"""
from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import db  # noqa: E402

OUT_PATH = db.PROJECT_ROOT / "supabase" / "01_schema.sql"

HEADER = """\
-- Replyworthy database for Supabase. Paste this whole file into the Supabase
-- SQL editor and press Run, ONCE, on a new empty project.
--
-- GENERATED by tools/build_supabase_sql.py from migrations/*.postgres.sql.
-- Do not edit by hand. It runs as one transaction: if anything fails,
-- nothing is created.

BEGIN;

CREATE TABLE schema_migrations (name TEXT PRIMARY KEY, applied_at TEXT NOT NULL);
"""


def build() -> str:
    parts = [HEADER]
    for path in sorted(db.MIGRATIONS_DIR.glob("*.postgres.sql")):
        name = path.name.split(".")[0]
        parts.append(f"\n-- ===== {name} =====\n")
        parts.append(path.read_text(encoding="utf-8").strip() + "\n")
        parts.append(
            "\nINSERT INTO schema_migrations (name, applied_at) VALUES "
            f"('{name}', to_char(now() AT TIME ZONE 'utc', "
            "'YYYY-MM-DD HH24:MI:SS'));\n"
        )
    parts.append("\nCOMMIT;\n")
    return "".join(parts)


def main() -> int:
    OUT_PATH.parent.mkdir(exist_ok=True)
    OUT_PATH.write_text(build(), encoding="utf-8", newline="\n")
    print(f"Wrote {OUT_PATH}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
